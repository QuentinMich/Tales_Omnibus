"""
Slugs gérés automatiquement : le client ne touche jamais à l'adresse d'une page.

- Pages à nom libre (fiches, campagnes) : le slug suit le titre. Renommer
  « Mon cul » en « Caer-Fiodh » change l'adresse en /caer-fiodh/.
- Pages uniques (Univers, Campagnes, Encyclopédie, Contact) : slug fixe, qui
  correspond au menu, quel que soit le titre choisi par le client.

Quand le slug d'une page PUBLIÉE change, l'app wagtail.contrib.redirects crée
toute seule une redirection 301 depuis l'ancienne adresse : les liens déjà
partagés continuent de marcher.
"""
from django.utils.text import slugify
from wagtail.admin.panels import FieldPanel, MultiFieldPanel


class SlugAutomatiqueMixin:
    """
    À mettre AVANT Page dans l'héritage : class HeroPage(SlugAutomatiqueMixin, Page).
    Pas un modèle Django : ce mixin n'ajoute aucun champ, donc aucune migration.
    """

    #: Slug imposé pour les pages uniques ; None = le slug suit le titre.
    slug_fixe = None

    promote_panels = [
        FieldPanel(
            "slug", read_only=True, heading="Adresse de la page",
            help_text="Générée automatiquement à partir du titre.",
        ),
        MultiFieldPanel([
            FieldPanel("seo_title", help_text=(
                "Laisser vide pour un titre automatique : "
                "« Titre de la page · Catégorie | Nom de l'univers »."
            )),
            FieldPanel("search_description", help_text=(
                "Laisser vide pour reprendre automatiquement l'accroche de la page "
                "(coupée à 155 caractères)."
            )),
        ], heading="Pour les moteurs de recherche"),
    ]

    def slug_voulu(self):
        # allow_unicode=False : « Encyclopédie » -> « encyclopedie » (sans accent,
        # donc pas de %C3%A9 dans la barre d'adresse)
        return self.slug_fixe or slugify(self.title or "", allow_unicode=False)

    def full_clean(self, *args, **kwargs):
        # full_clean est appelé par le formulaire de l'admin ET par save() :
        # c'est le seul endroit où intervenir pour couvrir tous les cas.
        base = self.slug_voulu()
        if base:
            parent_connu = bool(self.path or getattr(self, "_cached_parent_obj", None))
            # _get_autogenerated_slug (Wagtail) ajoute -2, -3… si une page sœur
            # a déjà ce slug ; sans parent connu on ne peut pas encore vérifier.
            self.slug = self._get_autogenerated_slug(base) if parent_connu else base
        super().full_clean(*args, **kwargs)
